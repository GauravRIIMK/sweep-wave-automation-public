# -*- coding: utf-8 -*-
"""Tone and voice doctrine, enforced as a blocking gate on every crafted mail.

WHY THIS IS A GATE AND NOT A PROMPT INSTRUCTION
-----------------------------------------------
craft.py already asks the model for a respectful, calm, specific mail. That is guidance,
and guidance is not enforcement: the mails that drew two tone complaints in one week were
generated by templates whose own validators approved them. The root cause recorded in
automail-pipeline/tone/ROOT_CAUSE_MEMO.md is exact -- every generator optimised each mail
for the SENDER'S honesty (state my count truthfully, get a clean no so I can stop, restate
the full case) and every validator enforced that. Read from the recipient's side, an honest
ledger of my persistence IS the pressure. No gate anywhere checked tone.

So the doctrine is machine-checked here, on the finished body, after the model is done.

THE STANDING VOICE (the thing every mail must sound like)
---------------------------------------------------------
Treat every recipient as CXO-level regardless of their actual title. Honest, warm, formal,
humble, specific. Show intelligence by being SHORT and by naming the one thing that is
genuinely relevant to them, never by displaying range. Non-response is a legitimate answer,
so each mail must cost the reader nothing: one ask, optional, ignorable, and then plain
thanks. Never a release tail, never a demand, never a ledger of what I have already sent.

SOURCE OF TRUTH
---------------
pipeline/tone_rules.json is VENDORED from automail-pipeline/tone/tone_gate_rules.json so
the GitHub runner needs no cross-repo access. Do not hand-edit the vendored copy: fix the
canonical file and re-vendor, or the two silently diverge.

WHAT THIS MODULE USED TO GET WRONG (fixed 2026-10-21)
-----------------------------------------------------
The rules file declares twelve STRUCTURAL rules. This engine executed exactly one of them
(S03, special-cased in _load). The other eleven were loaded, counted in the rule total,
and never evaluated. Four further defects sat in the regex path:

  1. `applies_to` was ignored, so T04_BOILERPLATE_CREDS -- severity BLOCK, scoped to
     [followup, final] -- fired on `initial` too. A first cold mail that legitimately
     states its credentials was blocked by a rule written to stop RE-stating them.
  2. Quoted thread history was never stripped, so a follow-up that quoted the previous
     mail was graded on that previous mail's prose as well as its own.
  3. The signature was never split off, so every rule scanned the sign-off block. The
     canonical engine deliberately scans only FORMAT and FACT rules there.
  4. Bodies were never line-flattened. Six patterns bound their span with [^.\n] to stay
     inside one sentence; Gmail hard-wraps at ~72 chars, so a wrap landing inside that
     span silently defeated the rule.

Rules needing context this engine cannot derive from the body alone (S04, S05, S06, S08,
S09, S12) are now reported as UNCHECKED rather than silently passed, which is the
canonical engine's stated contract. Supply the context via `ctx` and they become live.
S10_ORG_LOAD and S11_DRAFT_AGE are declared but unimplemented in BOTH engines; they are
reported as unimplemented so a report can never imply they ran.
"""
import io
import json
import os
import re

_HERE = os.path.dirname(os.path.abspath(__file__))
_RULES_PATH = os.path.join(_HERE, "tone_rules.json")
_HOLDS_PATH = os.path.join(os.path.dirname(_HERE), "state", "holds.json")

TOUCH_KINDS = ("initial", "followup", "final", "reply")

# Buckets in state/holds.json that genuinely suppress outbound mail.
# `replied` is NOT one: someone who answered is owed an answer, and suppressing them is
# how a live question gets buried. `review` is NOT one either: it is sediment from earlier
# runs rather than a decision, and treating it as a block silently retires 201 live leads.
SUPPRESSING_HOLD_BUCKETS = ("bounced", "capped", "closed")

# Rules declared in the file but implemented in NEITHER engine. Listed explicitly so a
# report says "unimplemented" instead of quietly counting them as passed.
UNIMPLEMENTED = ("S10_ORG_LOAD", "S11_DRAFT_AGE")

# Anchored to (?:\A|\n) rather than the canonical engine's bare \n. A draft whose very
# FIRST line is the quote marker -- a reply shell with nothing typed above it -- has no
# newline before the marker, so the canonical patterns miss it entirely and the gate then
# grades the mail on the QUOTED party's prose. That is how an empty reply shell came back
# blocked for T02_IMPERATIVE_DEMAND, a phrase the recipient wrote, not the sender.
_QUOTE_CUTS = [
    r"(?:\A|\n)On (?:Mon|Tue|Wed|Thu|Fri|Sat|Sun),? ",
    r"(?:\A|\n)On \d{1,2} [A-Z][a-z]{2} ",
    r"(?:\A|\n)On \d{4}-\d{2}-\d{2}",
    r"(?:\A|\n)From: ",
    r"(?:\A|\n)-{3,} ?Original Message",
    r"(?:\A|\n)_{20,}",
    r"(?:\A|\n)> ",
    r"(?:\A|\n)[^\n]{0,80}<[^>\s]+@[^>\s]+> wrote:",
    r"(?:\A|\n)[^\n]{0,80} wrote:\s*\n",
]

_CACHE = None
_HOLDS_CACHE = None


def _flags(spec):
    """Honour the rule's own flag string. Dropping a flag silently weakens the rule:
    T07_PS_LINE declares "im" and is anchored with ^, so losing MULTILINE made it match
    only a P.S. at the very start of the body, i.e. never."""
    spec = spec or ""
    f = 0
    if "i" in spec:
        f |= re.I
    if "m" in spec:
        f |= re.M
    if "s" in spec:
        f |= re.S
    return f


def strip_quoted_history(text):
    """Return only the sender's own part of a body, dropping quoted thread history.

    Without this the gate grades a follow-up on the prose of the mail it quotes, which is
    both a false positive (the old mail's banned phrasing is attributed to the new one)
    and a false reading of length.
    """
    t = (text or "").replace("\r", "")
    cut = len(t)
    for pat in _QUOTE_CUTS:
        m = re.search(pat, t)
        # Cut when the marker sits after real content, OR when everything before it is
        # whitespace (an empty reply shell: Gmail's "On <date> ... wrote:" with nothing
        # typed above it).
        if m and (m.start() > 60 or not t[:m.start()].strip()):
            cut = min(cut, m.start())
    return t[:cut].strip()


def split_signature(own_text, markers):
    """Split into (content, signature) at the earliest sign-off marker in the last 45%.

    The 45% floor matters: "Thanks," early in a sentence is prose, not a sign-off, and
    cutting there would hide most of the body from the rules that read `content`.

    The marker must also sit ALONE on its line. The canonical engine tests only the 45%
    floor, which misreads a late prose line such as "Thanks, and congratulations on the
    Series F. Please revert with a clear yes or no." as a sign-off and moves the demand in
    its tail out of `content`, under-counting S07's word budget. A real sign-off is always
    the whole line; verified against all 63 mails sent 2026-10-10, where the marker is
    alone on its line in 63 of 63 and this requirement changes no word count.
    """
    t = own_text
    n = len(t)
    best = None
    for mk in markers:
        start = 0
        while True:
            i = t.find(mk, start)
            if i < 0:
                break
            start = i + 1
            if i < n * 0.55:
                continue
            ls = t.rfind("\n", 0, i) + 1
            if t[ls:].splitlines()[0].strip() != mk.strip():
                continue
            if best is None or i < best:
                best = i
    if best is None:
        m = re.search(r"\n\s*Gaurav(?: Rathore)?\s*$", t)
        if m and m.start() >= n * 0.55:
            best = m.start()
    if best is None:
        return t.strip(), ""
    return t[:best].strip(), t[best:].strip()


def sentences(text):
    t = re.sub(r"\s+", " ", (text or "").strip())
    if not t:
        return []
    return [p.strip() for p in re.split(r"(?<=[.?!])\s+(?=[A-Z0-9\"'(])", t) if p.strip()]


def _load():
    global _CACHE
    if _CACHE is None:
        raw = json.load(io.open(_RULES_PATH, encoding="utf-8-sig"))
        compiled = []
        for r in raw.get("regex_rules", []):
            pat = r.get("pattern")
            if not pat:
                continue
            try:
                rx = re.compile(pat, _flags(r.get("flags")))
            except re.error as e:
                # A broken pattern must be loud. Silently skipping it would remove a
                # guard while every report still says the gate ran.
                raise RuntimeError("tone rule %s failed to compile: %s" % (r.get("id"), e))
            compiled.append((r, rx))

        struct = dict((s["id"], s) for s in raw.get("structural_rules", []))

        ad = raw.get("ask_detection") or {}
        af = _flags(ad.get("flags") or "i")
        asks = [re.compile(p, af) for p in (ad.get("ask_patterns") or []) if p]
        rels = [re.compile(p, af) for p in (ad.get("release_patterns") or []) if p]

        _CACHE = (raw.get("version"), compiled, struct, asks, rels,
                  raw.get("signature_markers") or [])
    return _CACHE


def rules_version():
    return _load()[0]


def _severity(sev, by_touch, touch):
    # A rule may be flat ("block") or vary by touch kind. Unknown resolves to "block":
    # for a gate whose failure mode is a damaged relationship, the safe default is to
    # refuse, not to allow. The canonical engine defaults to "warn" here; every rule in
    # the current file declares all four touch kinds, so the divergence is unreachable
    # today, but this side stays fail-closed on purpose.
    if by_touch:
        return by_touch.get(touch, "block")
    return sev or "block"


def _sev_of(rule, touch):
    return _severity(rule.get("severity"), rule.get("severity_by_touch") or {}, touch)


def _applies(rule, touch):
    return touch in (rule.get("applies_to") or TOUCH_KINDS)


def load_holds(path=None):
    """Suppression feed for S09, derived from the pipeline's own hold store.

    Parsed as JSON, never grepped: a substring search over this file matches a domain
    inside an unrelated address and blocks a live lead.
    """
    global _HOLDS_CACHE
    if path is not None:
        return _read_holds(path)
    if _HOLDS_CACHE is None:
        _HOLDS_CACHE = _read_holds(_HOLDS_PATH)
    return _HOLDS_CACHE


def _read_holds(p):
    try:
        h = json.load(io.open(p, encoding="utf-8-sig"))
    except Exception:
        # Returning None (not {}) matters: an unreadable store must read as UNCHECKED,
        # never as "nobody is suppressed".
        return None
    out = {}
    for bucket in SUPPRESSING_HOLD_BUCKETS:
        v = h.get(bucket)
        if isinstance(v, dict):
            v = list(v.keys())
        for addr in (v or []):
            if isinstance(addr, str) and "@" in addr:
                out[addr.strip().lower()] = bucket
    return out


def is_suppressed(email, suppression):
    """Exact-address match only.

    Deliberately NOT a substring or domain test: a substring ban on `lever.co` once
    blocked every `unilever.com` address. Domain-level suppression is a separate decision
    recorded per address by the sweep, not inferred here.
    """
    if not email or not suppression:
        return None
    hit = suppression.get(email.strip().lower())
    return ("%s (%s)" % (email, hit)) if hit else None


def tone_report(body, touch="followup", ctx=None, subject=None):
    """Full gate result for a finished mail body.

    Returns a dict shaped like the canonical engine's `check()`:
      ok, touch, rules_version, blocks, warns, unchecked,
      ask_count, asks, release_found, word_count, content_preview

    `ctx` carries what the body cannot tell us. Every key is optional; an absent key puts
    its rule in `unchecked` rather than passing it:
      new_info (str)        -> S04      prior_bodies (list[str]) -> S05
      prior_ask_count (int) -> S06      touch_number (int)       -> S08
      to (str)              -> S09 (suppression loads from state/holds.json unless the
                                    caller passes `suppression`)
      suppression (dict)    -> S09 override, as returned by load_holds()
    """
    if touch not in TOUCH_KINDS:
        raise ValueError("touch must be one of %s" % (TOUCH_KINDS,))
    ctx = ctx or {}
    version, compiled, struct, ask_rx, rel_rx, sig_markers = _load()

    own = strip_quoted_history(body)
    content, sig = split_signature(own, sig_markers)
    blocks, warns, unchecked = [], [], []

    def add(rule_id, message, match, sev):
        line = "%s: %s" % (rule_id, (message or "").split(".")[0])
        if match:
            line += " [%r]" % str(match)[:80]
        (blocks if sev == "block" else warns).append(line)

    # An empty own-part is a defect, never a pass. A reply shell whose only text is the
    # quoted thread reads as non-empty to a naive length check and would send blank.
    if not content.strip():
        add("S00_EMPTY_BODY",
            "Draft has no content of its own (empty reply shell or blank draft); never send",
            "", "block")

    # Regex rules scan the sender's ENTIRE own text, signature included.
    #
    # The canonical engine restricts everything except FORMAT and FACT to `content`, i.e.
    # above the sign-off. Porting that faithfully opened a fail-open hole, found by review
    # on 2026-10-22: a P.S. after the sign-off is prose the recipient reads, but it sat in
    # the unscanned region, so
    #     "P.S. Even a one line no would help me a great deal."
    # passed with ok=True and an empty block list, while the identical sentence placed
    # above the sign-off blocked on T02_DEMAND_REJECTION and T02_GREAT_DEAL. T07_PS_LINE
    # does not save it either: that rule is family ESCALATION, not FORMAT.
    #
    # This also restores the pre-2026-10-21 sweep-wave behaviour, which scanned the whole
    # body, so widening here is a repair rather than a new divergence. Measured cost on the
    # 63 mails actually sent 2026-10-10: ZERO new blocking hits, because the signature is
    # fixed contact boilerplate that trips no rule.
    #
    # Non-anchored patterns scan a line-flattened copy so a Gmail hard-wrap cannot fall
    # inside a [^.\n]-bounded span and defeat the rule.
    flat_content = re.sub(r"[ \t]*\n[ \t]*", " ", content)
    flat_own = re.sub(r"[ \t]*\n[ \t]*", " ", own)
    for rule, rx in compiled:
        if not _applies(rule, touch):
            continue
        anchored = ("m" in (rule.get("flags") or "")) or rule["pattern"].startswith("^")
        scan = own if anchored else flat_own
        hits = [m.group(0) for m in rx.finditer(scan)]
        if hits:
            sev = _sev_of(rule, touch)
            for h in hits[:6]:
                add(rule["id"], rule.get("message", ""), h.strip(), sev)

    # ---- ask detection, the shared input to S01/S02/S03/S06
    #
    # Counted over `own`, not `content`, for the same reason the regex rules are: an ask in
    # a P.S. below the sign-off is still an ask the recipient has to field, and counting
    # only above the sign-off let a second ask ride along uncounted past S01's budget of
    # one. Identical on all 63 real mails, so this costs nothing on reviewed copy.
    #
    # S05 keeps using the content-only sentence list below: it compares against my prior
    # outbound, and a signature repeated verbatim in every mail would register as repeated
    # prose in every follow-up.
    sents = sentences(content)
    sents_own = sentences(own)
    asks = [s for s in sents_own if any(r.search(s) for r in ask_rx)]
    ask_count = len(asks)
    release_hit = None
    for r in rel_rx:
        m = r.search(flat_own)
        if m:
            release_hit = m.group(0)
            break
    release = release_hit is not None

    # S01 / S02 are mutually exclusive: on a final touch the budget is zero asks, on every
    # other touch it is one. Running both would double-report the same sentence.
    s01, s02 = struct.get("S01_MAX_ASKS"), struct.get("S02_FINAL_NO_ASK")
    if touch == "final" and s02 and _applies(s02, touch):
        if ask_count > int(s02.get("param", 0)):
            add(s02["id"], s02.get("message"), " | ".join(asks[:3]), _sev_of(s02, touch))
    elif s01 and _applies(s01, touch):
        if ask_count > int(s01.get("param", 1)):
            add(s01["id"], s01.get("message"), " | ".join(asks[:3]), _sev_of(s01, touch))

    # S03 release tail is BANNED (inverted 2026-08-26). Fires when a release IS present,
    # on any touch, ask or no ask. The release tail was REQUIRED until that date, so old
    # copy is full of it.
    s03 = struct.get("S03_RELEASE_TAIL_BANNED") or struct.get("S03_ASK_NEEDS_RELEASE")
    if s03 and _applies(s03, touch) and release:
        add(s03["id"], s03.get("message"), release_hit or "", _sev_of(s03, touch))

    # S04 a follow-up must carry a concrete new data point, verbatim in the body.
    s04 = struct.get("S04_FOLLOWUP_NEEDS_NEW_INFO")
    if s04 and _applies(s04, touch):
        if "new_info" not in ctx:
            unchecked.append("%s: no new_info supplied" % s04["id"])
        else:
            ni = re.sub(r"\s+", " ", (ctx.get("new_info") or "").strip())
            if not ni:
                add(s04["id"], s04.get("message"), "new_info empty", _sev_of(s04, touch))
            elif ni[:40].lower() not in re.sub(r"\s+", " ", flat_content).lower():
                add(s04["id"], s04.get("message"),
                    "new_info text not found in body: " + ni[:60], _sev_of(s04, touch))

    # S05 do not re-send sentences the recipient has already read from me.
    s05 = struct.get("S05_REPEAT_SENTENCES")
    if s05 and _applies(s05, touch):
        if "prior_bodies" not in ctx:
            unchecked.append("%s: no prior_bodies supplied" % s05["id"])
        else:
            p = s05.get("param") or {}
            min_words = int(p.get("min_words", 8))
            max_rep = int(p.get("max_repeated_sentences", 1))
            prior_norm = " ".join(
                re.sub(r"\s+", " ", strip_quoted_history(b)).lower()
                for b in (ctx.get("prior_bodies") or []))
            repeated = []
            for s in sents:
                if len(s.split()) >= min_words:
                    key = re.sub(r"\s+", " ", s).lower().rstrip(".")
                    if key and key in prior_norm:
                        repeated.append(s)
            if len(repeated) > max_rep:
                add(s05["id"], s05.get("message"), " | ".join(repeated[:3]),
                    _sev_of(s05, touch))

    # S06 the ask must never grow across touches.
    s06 = struct.get("S06_ESCALATING_ASK")
    if s06 and _applies(s06, touch):
        if ctx.get("prior_ask_count") is None:
            unchecked.append("%s: no prior_ask_count supplied" % s06["id"])
        elif ask_count > int(ctx["prior_ask_count"]):
            add(s06["id"], s06.get("message"),
                "asks %d > previous %d" % (ask_count, ctx["prior_ask_count"]),
                _sev_of(s06, touch))

    # S07 word budget, measured on content only. A mail that names a live requisition gets
    # a larger budget because the URL and the verbatim title are load-bearing, not padding.
    s07 = struct.get("S07_MAX_WORDS")
    wc = len(re.findall(r"\b\w[\w'&%+/.-]*\b", content))
    if s07 and _applies(s07, touch):
        p07 = s07.get("param") or {}
        limit = int(p07.get(touch, 999))
        rbm = p07.get("role_block_marker")
        if rbm and touch in ("followup", "final") and re.search(rbm, content, re.I):
            limit = int(p07.get(touch + "_with_role_block", limit))
        if wc > limit:
            add(s07["id"], s07.get("message"), "%d words > %d" % (wc, limit),
                _sev_of(s07, touch))

    # S08 hard cap on total touches per human.
    s08 = struct.get("S08_TOUCH_CAP")
    if s08 and _applies(s08, touch):
        if ctx.get("touch_number") is None:
            unchecked.append("%s: no touch_number supplied" % s08["id"])
        else:
            cap = int(s08.get("param", 3))
            if int(ctx["touch_number"]) > cap:
                add(s08["id"], s08.get("message"),
                    "touch %s of cap %s" % (ctx["touch_number"], cap), _sev_of(s08, touch))

    # S09 never mail a suppressed address.
    s09 = struct.get("S09_SUPPRESSED")
    if s09 and _applies(s09, touch):
        sup = ctx.get("suppression")
        if sup is None:
            sup = load_holds()
        to = ctx.get("to")
        if not to:
            unchecked.append("%s: no recipient supplied" % s09["id"])
        elif sup is None:
            unchecked.append("%s: suppression store unreadable" % s09["id"])
        else:
            hit = is_suppressed(to, sup)
            if hit:
                add(s09["id"], s09.get("message"), hit, _sev_of(s09, touch))

    # S12 role titles must match the verified registry. The registry lives in the
    # canonical repo (automail-pipeline/tone/roles_registry.json) and is NOT vendored
    # here, so this rule cannot run in sweep-wave. Reported, never assumed passed.
    s12 = struct.get("S12_ROLE_TITLE_VERBATIM")
    if s12 and _applies(s12, touch):
        unchecked.append("%s: roles_registry.json is not vendored into sweep-wave; run "
                         "tone_gate.py in automail-pipeline to check role titles"
                         % s12["id"])

    for rid in UNIMPLEMENTED:
        if rid in struct and _applies(struct[rid], touch):
            unchecked.append("%s: declared in the rules file, implemented in neither "
                             "engine" % rid)

    return {
        "ok": not blocks,
        "touch": touch,
        "rules_version": version,
        "blocks": blocks,
        "warns": warns,
        "unchecked": unchecked,
        "ask_count": ask_count,
        "asks": asks,
        "release_found": release,
        "word_count": wc,
        "content_preview": content[:160],
    }


def tone_violations(body, touch="followup", ctx=None, subject=None):
    """Return (blocking: [str], warnings: [str]) for a finished mail body.

    `touch` selects the severity column for rules that vary by touch kind. "followup" is
    the strictest realistic default and the one this pipeline actually sends, so it is the
    default here rather than "initial".

    Kept as a 2-tuple because dispatch.py and validate.py both unpack two values. Callers
    that need the ask count, the word count or the UNCHECKED list should call
    tone_report(). Unchecked rules are folded into `warnings` here so they are present in
    the 2-tuple at all, but both current callers discard warnings: read tone_report() if
    you need to know what did not run.
    """
    r = tone_report(body, touch=touch, ctx=ctx, subject=subject)
    warnings = list(r["warns"])
    if r["unchecked"]:
        warnings.append("UNCHECKED (%d): %s" % (len(r["unchecked"]),
                                                "; ".join(r["unchecked"])))
    return r["blocks"], warnings
